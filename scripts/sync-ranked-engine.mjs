import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const modules = ['types', 'balance', 'deterministicMath', 'difficulty', 'random', 'engine'];
const check = process.argv.includes('--check');
if (process.argv.slice(2).some(argument => argument !== '--check')) {
  throw new Error('Only --check is supported.');
}
const sources = [];
const hash = createHash('sha256');
for (const name of modules) {
  const filename = `src/game/${name}.ts`;
  const source = (await readFile(resolve(root, filename), 'utf8')).replace(/\r\n?/g, '\n').replace(/\n*$/, '\n');
  const imports = [...source.matchAll(/\bfrom\s+['"]([^'"]+)['"]/g)].map(match => match[1]);
  if (imports.some(specifier => !modules.some(module => specifier === `./${module}`)) ||
      /\b(?:require\s*\(|import\s*\(|Date\s*\.|Math\s*\.\s*(?:random|sin|log|log1p)\s*\(|Deno\s*\.|process\s*\.)/.test(source) ||
      /\bimport\s+['"]/.test(source)) {
    throw new Error(`Noncanonical or platform-dependent dependency in ${filename}`);
  }
  hash.update(filename).update('\0').update(source).update('\0');
  sources.push([name, source]);
}
const version = `nyang-v1-${hash.digest('hex').slice(0, 16)}`;
const header = '// Generated by scripts/sync-ranked-engine.mjs. Do not edit.\n';
const outputs = sources.map(([name, source]) => [
  `supabase/functions/_shared/game/${name}.ts`,
  header + source.replace(/(\bfrom\s+['"])(\.\/[^'"]+)(['"])/g, '$1$2.ts$3'),
]);
const versionSource = `${header}export const RULES_VERSION = '${version}';\n`;
outputs.push(['src/online/rulesVersion.ts', versionSource]);
outputs.push(['supabase/functions/_shared/game/rulesVersion.ts', versionSource]);
const drift = [];
for (const [filename, expected] of outputs) {
  const destination = resolve(root, filename);
  if (check) {
    const actual = await readFile(destination, 'utf8').catch(() => null);
    // Git's Windows checkout may use CRLF; source hashing is LF-normalized too.
    if (actual === null || actual.replace(/\r\n?/g, '\n') !== expected) drift.push(filename);
  } else {
    await mkdir(dirname(destination), { recursive: true });
    await writeFile(destination, expected, 'utf8');
  }
}
if (drift.length) {
  throw new Error(`Ranked engine drift. Run npm run ranked:sync:\n${drift.join('\n')}`);
}
console.log(`${check ? 'Checked' : 'Generated'} ${outputs.length} canonical files: ${version}`);
